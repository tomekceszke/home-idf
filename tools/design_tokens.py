#!/usr/bin/env python3
"""Design tokens for pages and panels (design/README.md).

  design_tokens.py header <view> OUT.h   C header for a panel (LVGL or not): colours, geometry, layout, labels, icons
  design_tokens.py css <view> OUT.css    :root block with the family's and the view's colours (for an app page)
  design_tokens.py check                 exit 1 when design/tokens.json and the :root of web/app_shell.css differ

Used at build time by home_idf_design() and in CI (check). Pure standard library.
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DESIGN = ROOT / "design"


def load(view=None):
    tokens = json.loads((DESIGN / "tokens.json").read_text("utf-8"))
    if view is None:
        return tokens, None
    path = DESIGN / "views" / view / "view.json"
    if not path.is_file():
        raise SystemExit(f"design_tokens.py: no view {view!r} ({path})")
    return tokens, json.loads(path.read_text("utf-8"))


def public(d):
    return {k: v for k, v in d.items() if not k.startswith("_")}


def colors(tokens, view):
    """Every colour a view may name: the family's, overridden and extended by the view's."""
    out = dict(tokens["color"])
    if view:
        out.update(public(view.get("colors", {})))
    return out


def ident(name):
    return re.sub(r"[^A-Za-z0-9]", "_", name).upper()


def c_string(text):
    """A C string literal; non-ASCII as UTF-8 octal escapes (at most three digits, so the next character is never
    read as part of the escape and no literal has to be split)."""
    out = []
    for ch in text:
        if ch == '"' or ch == "\\":
            out.append("\\" + ch)
        elif 32 <= ord(ch) < 127:
            out.append(ch)
        else:
            out.append("".join(f"\\{b:03o}" for b in ch.encode("utf-8")))
    return '"' + "".join(out) + '"'


def hex_color(value, palette):
    value = palette.get(value, value)
    if not re.fullmatch(r"#[0-9a-fA-F]{6}", value):
        raise SystemExit(f"design_tokens.py: {value!r} is neither a colour nor a token")
    return "0x" + value[1:].lower()


def icon_utf8(view, name):
    if name is None:
        return '""'
    return c_string(chr(int(view["icons"][name], 16)))


def header(view_name):
    tokens, view = load(view_name)
    pal = colors(tokens, view)
    v = ident(view_name)
    lines = [
        "/* Generated by home-idf tools/design_tokens.py from design/tokens.json and "
        f"design/views/{view_name}/view.json: do not edit. */",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        "/* Colours as 0xRRGGBB (lv_color_hex()) */",
    ]
    lines += [f"#define HI_COLOR_{ident(k)} {hex_color(c, pal)}" for k, c in pal.items()]

    lines += ["", f"/* {view_name}: range and format */"]
    for k, val in public(view.get("range", {})).items():
        lines.append(f"#define HI_{v}_{ident(k)} {val}")
    fmt = public(view.get("format", {}))
    for k, val in fmt.items():
        lines.append(f"#define HI_{v}_{ident(k)} " + (c_string(val) if isinstance(val, str) else str(val)))

    def numbers(prefix, d):
        for k, val in public(d).items():
            if isinstance(val, dict):
                numbers(f"{prefix}_{ident(k)}", val)
            elif isinstance(val, bool):
                continue
            elif isinstance(val, (int, float)):
                lines.append(f"#define {prefix}_{ident(k)} {val}")
            elif isinstance(val, str) and (k == "color" or k.endswith("_color") or k == "bg"):
                lines.append(f"#define {prefix}_{ident(k)} {hex_color(val, pal)}")

    if "interaction" in view:
        lines += ["", f"/* {view_name}: changing the set point */"]
        numbers(f"HI_{v}_INTERACTION", view["interaction"])
    if "dial" in view:
        lines += ["", f"/* {view_name}: dial at the base size (scale by size / BASE) */"]
        numbers(f"HI_{v}_DIAL", view["dial"])
    if "panel" in view:
        lines += ["", f"/* {view_name}: 480x480 panel layout */"]
        numbers(f"HI_{v}_PANEL", {k: val for k, val in view["panel"].items() if k not in ("fonts", "glyph_sets")})

    lines += ["", "/* Icons (Material Symbols Rounded) as UTF-8 */"]
    lines += [f"#define HI_ICON_{ident(k)} {icon_utf8(view, k)}" for k in public(view.get("icons", {}))]

    def text(d):
        return c_string(d["pl"])

    if "states" in view:
        lines += ["", "typedef struct {", "    const char *key;", "    uint32_t arc;", "    const char *icon;",
                  "    uint32_t icon_color;", "    uint32_t label_color;",
                  "    const char *headline;   /* {0} = burner %, DHW temperature, fault code */",
                  "    const char *label;", "    const char *detail;     /* panel: muted, after the label; {0} as above */",
                  f"}} hi_{view_name}_state_t;", "",
                  f"static const hi_{view_name}_state_t HI_{v}_STATES[] = {{"]
        for key, s in public(view["states"]).items():
            lines.append(f"    {{{c_string(key)}, {hex_color(s['arc'], pal)}, {icon_utf8(view, s['icon'])}, "
                         f"{hex_color(s['icon_color'], pal)}, {hex_color(s['label_color'], pal)}, "
                         f"{text(s['headline'])}, {text(s['short'])}, {text(s['detail'])}}},")
        lines.append("};")
    if "modes" in view:
        lines += ["", "typedef struct {", "    const char *key;", "    const char *icon;", "    const char *label;",
                  "    const char *short_label;", f"}} hi_{view_name}_mode_t;", "",
                  f"static const hi_{view_name}_mode_t HI_{v}_MODES[] = {{"]
        for key, m in public(view["modes"]).items():
            lines.append(f"    {{{c_string(key)}, {icon_utf8(view, m['icon'])}, {text(m['label'])}, "
                         f"{text(m.get('short', m['label']))}}},")
        lines.append("};")
    for table in ("faults", "sources"):
        if table in view:
            lines += ["", f"static const char *const HI_{v}_{ident(table)}[][2] = {{"]
            lines += [f"    {{{c_string(k)}, {text(t)}}}," for k, t in public(view[table]).items()]
            lines.append("};")
    if "texts" in view:
        lines += [""]
        for k, t in public(view["texts"]).items():
            if isinstance(t["pl"], list):
                items = ", ".join(c_string(s) for s in t["pl"])
                lines.append(f"static const char *const HI_{v}_TEXT_{ident(k)}[] = {{{items}}};")
            else:
                lines.append(f"#define HI_{v}_TEXT_{ident(k)} {text(t)}")
    return "\n".join(lines) + "\n"


def css(view_name):
    tokens, view = load(view_name)
    pal = colors(tokens, view)
    decls = [f"--{k}: {c};" for k, c in pal.items()]
    return f":root {{ {' '.join(decls)} }}\n"


def shell_root():
    text = (ROOT / "web" / "app_shell.css").read_text("utf-8")
    block = re.search(r":root\s*\{([^}]*)\}", text).group(1)
    return dict(re.findall(r"--([a-z-]+):\s*([^;]+);", block))


def check():
    tokens, _ = load()
    shell = shell_root()
    want = {**tokens["color"], **{k: f"{v}px" for k, v in tokens["size"].items()}}
    bad = [f"--{k}: tokens.json {v}, app_shell.css {shell.get(k)}" for k, v in want.items() if shell.get(k) != str(v)]
    if bad:
        raise SystemExit("design tokens and web/app_shell.css differ:\n  " + "\n  ".join(bad))
    print(f"design tokens match web/app_shell.css ({len(want)} values)")


if __name__ == "__main__":
    args = sys.argv[1:]
    if args[:1] == ["check"] and len(args) == 1:
        check()
    elif len(args) == 3 and args[0] in ("header", "css"):
        out = pathlib.Path(args[2])
        out.parent.mkdir(parents=True, exist_ok=True)
        content = header(args[1]) if args[0] == "header" else css(args[1])
        if not out.exists() or out.read_text("utf-8") != content:
            out.write_text(content, "utf-8")
    else:
        raise SystemExit(__doc__)
